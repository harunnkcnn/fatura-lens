export const dictionaries: Record<Locale, Dict> = { tr, en };

export function detectLocale(): Locale {
  try {
    const saved = localStorage.getItem('fl.locale');
    if (saved === 'tr' || saved === 'en') return saved;
  } catch {
    /* storage unavailable */
  }
  return navigator.language.toLowerCase().startsWith('tr') ? 'tr' : 'en';
}

export function describeFinding(t: Dict, f: Finding): string {
  return t.findings[f.code](f.params ?? {});
}

export function moneyFormatter(locale: Locale) {
  const nf = new Intl.NumberFormat(locale === 'tr' ? 'tr-TR' : 'en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 });
  return (n: number | null | undefined) => (n === null || n === undefined ? '—' : nf.format(n));
}

export function numberFormatter(locale: Locale) {
  const nf = new Intl.NumberFormat(locale === 'tr' ? 'tr-TR' : 'en-US', { maximumFractionDigits: 4 });
  return (n: number | null | undefined) => (n === null || n === undefined ? '—' : nf.format(n));
}

export function dateFormatter(locale: Locale) {
  return (iso: string) => {
    const m = /^(\d{4})-(\d{2})-(\d{2})/.exec(iso);
    if (!m) return iso || '—';
    return locale === 'tr' ? `${m[3]}.${m[2]}.${m[1]}` : `${m[1]}-${m[2]}-${m[3]}`;
  };
}
